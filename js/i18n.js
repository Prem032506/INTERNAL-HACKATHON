class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('global_setu_lang') || 'en';
    this.listeners = [];
  }

  setLanguage(lang) {
    if (I18N_DICTIONARY[lang]) {
      this.currentLang = lang;
      localStorage.setItem('global_setu_lang', lang);
      this.applyTranslations();
      window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: this.currentLang } }));
      this.listeners.forEach(fn => {
        try { fn(this.currentLang); } catch (e) { console.error('[I18n] Listener error:', e); }
      });
      return true;
    }
    return false;
  }

  onLanguageChange(fn) {
    if (typeof fn === 'function') {
      this.listeners.push(fn);
    }
  }

  get(key) {
    const dict = I18N_DICTIONARY[this.currentLang] || I18N_DICTIONARY['en'];
    if (dict && dict[key] !== undefined) return dict[key];
    if (I18N_DICTIONARY['en'] && I18N_DICTIONARY['en'][key] !== undefined) return I18N_DICTIONARY['en'][key];
    return key;
  }

  applyTranslations() {
    // 1. Text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        const val = this.get(key);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.value = val;
        } else {
          el.textContent = val;
        }
      }
    });

    // 2. HTML elements with data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (key) {
        el.innerHTML = this.get(key);
      }
    });

    // 3. Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.placeholder = this.get(key);
      }
    });

    // 4. Tooltip / Title attributes
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (key) {
        el.title = this.get(key);
      }
    });

    // 5. Select optgroup labels
    document.querySelectorAll('optgroup[data-i18n-label]').forEach(el => {
      const key = el.getAttribute('data-i18n-label');
      if (key) {
        el.label = this.get(key);
      }
    });

    // 6. Active language name badge in navbar
    const activeLangName = document.getElementById('current-lang-name');
    if (activeLangName) {
      const langNames = {
        en: 'EN (Global)',
        es: 'ES (Español)',
        fr: 'FR (Français)',
        de: 'DE (Deutsch)',
        ja: 'JA (日本語)',
        zh: 'ZH (中文)',
        ar: 'AR (العربية)',
        hi: 'HI (हिन्दी)',
        as: 'AS (অসমীয়া)',
        bn: 'BN (বাংলা)',
        mni: 'MNI (মৈতৈ)'
      };
      activeLangName.textContent = langNames[this.currentLang] || 'EN';
    }

    // 7. Update document language
    document.documentElement.lang = this.currentLang;
    if (this.currentLang === 'ar') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }
  }
}

window.i18n = new I18nManager();
