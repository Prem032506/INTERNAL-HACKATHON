class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('global_setu_lang') || 'en';
  }

  setLanguage(lang) {
    if (I18N_DICTIONARY[lang]) {
      this.currentLang = lang;
      localStorage.setItem('global_setu_lang', lang);
      this.applyTranslations();
      return true;
    }
    return false;
  }

  get(key) {
    const dict = I18N_DICTIONARY[this.currentLang] || I18N_DICTIONARY['en'];
    return dict[key] || I18N_DICTIONARY['en'][key] || key;
  }

  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = this.get(key);
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.placeholder = this.get(key);
      }
    });

    const activeLangName = document.getElementById('current-lang-name');
    if (activeLangName) {
      const langNames = {
        en: 'EN (Global)',
        es: 'ES (Español)',
        fr: 'FR (Français)',
        de: 'DE (Deutsch)',
        ja: 'JA (日本語)',
        zh: 'ZH (中文)',
        ar: 'AR (العربية)',
        hi: 'HI (हिन्दी)',
        as: 'AS (অসমীয়া)',
        bn: 'BN (বাংলা)',
        mni: 'MNI (মৈতৈ)'
      };
      activeLangName.textContent = langNames[this.currentLang] || 'EN';
    }
  }
}

window.i18n = new I18nManager();
